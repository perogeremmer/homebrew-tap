  on_macos do
    url "https://github.com/perogeremmer/hakonfig/releases/download/v0.6.3/hakonfig-cli-universal-apple-darwin"
    sha256 "91e2ed135d75bdeccfad95a7f2b488bf3fd6b49fd6eb14bb8d9194d218502637"

